-- Application layer: churn model scores (populated by train job)

CREATE TABLE IF NOT EXISTS APP_CUSTOMER_CHURN_SCORES (
    CUSTOMER_ID           INTEGER NOT NULL PRIMARY KEY,
    CHURN_PROBABILITY     REAL NOT NULL,
    CHURN_RISK_TIER       TEXT NOT NULL,
    MODEL_VERSION         TEXT NOT NULL,
    SCORED_AT             TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_churn_tier ON APP_CUSTOMER_CHURN_SCORES (CHURN_RISK_TIER);
