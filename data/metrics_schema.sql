-- Application-layer caches (refreshed after warehouse seed / churn train)

CREATE TABLE IF NOT EXISTS APP_CUSTOMER_METRICS (
    CUSTOMER_ID             INTEGER NOT NULL PRIMARY KEY,
    POLICY_COUNT            INTEGER NOT NULL,
    INVESTMENT_TRACK_COUNT  INTEGER NOT NULL,
    CUSTOMER_VALUE          REAL NOT NULL,
    REFRESHED_AT            TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_customer_metrics_value ON APP_CUSTOMER_METRICS (CUSTOMER_VALUE DESC);

CREATE TABLE IF NOT EXISTS APP_OVERVIEW_COUNTS (
    FILTER_KEY    TEXT NOT NULL PRIMARY KEY,
    ROW_COUNT     INTEGER NOT NULL,
    REFRESHED_AT  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS APP_PORTFOLIO_ANALYTICS_CACHE (
    SEGMENT         TEXT NOT NULL PRIMARY KEY,
    PAYLOAD_JSON    TEXT NOT NULL,
    REFRESHED_AT    TEXT NOT NULL
);

-- Book-wide strategic objective trends (materialized; shared across cohort filters)
CREATE TABLE IF NOT EXISTS APP_BOOK_SAVINGS_AUM_TREND (
    PERIOD               TEXT NOT NULL PRIMARY KEY,
    ACCUMULATION_TOTAL   REAL NOT NULL,
    ACTIVE_SAVERS        INTEGER NOT NULL,
    SAVINGS_POLICIES     INTEGER NOT NULL,
    REFRESHED_AT         TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS APP_BOOK_PREMIUM_MOMENTUM_TREND (
    PERIOD                  TEXT NOT NULL PRIMARY KEY,
    ACTIVE_POLICY_COUNT     INTEGER NOT NULL,
    MONTHLY_PREMIUM_TOTAL   REAL NOT NULL,
    REFRESHED_AT            TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS APP_BOOK_ENGAGEMENT_TREND (
    PERIOD                TEXT NOT NULL PRIMARY KEY,
    INTERACTION_EVENTS    INTEGER NOT NULL,
    DIGITAL_TOUCHPOINTS   INTEGER NOT NULL,
    REVIEW_EVENTS         INTEGER NOT NULL,
    REFRESHED_AT          TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS APP_WAREHOUSE_TABLE_MANIFEST (
    TABLE_NAME      TEXT NOT NULL PRIMARY KEY,
    LAYER           TEXT NOT NULL,
    DOMAIN          TEXT NOT NULL,
    ROW_COUNT       INTEGER NOT NULL,
    LAST_LOADED_AT  TEXT NOT NULL,
    SOURCE_JOB      TEXT NOT NULL
);

-- Query paths used heavily at scale
CREATE INDEX IF NOT EXISTS idx_pit_customer_snapshot
    ON DWH_FCT_POLICY_INVESTMENT_TRACK (CUSTOMER_ID, SNAPSHOT_DATE);

CREATE INDEX IF NOT EXISTS idx_policy_status_customer_period
    ON DWH_FCT_POLICY_STATUS (CUSTOMER_ID, SNAPSHOT_DATE);

CREATE INDEX IF NOT EXISTS idx_policy_customer_mng
    ON DWH_DIM_ALL_POLICY (CUSTOMER_ID, MNG_COMPANY_CODE, IS_ACTIVE);
